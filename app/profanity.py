"""Фильтр нецензурной лексики для комментариев (ru / kk / en).

Как работает:

1. Текст приводится к «нормальной» форме для поиска: нижний регистр,
   «ё» -> «е», латинские буквы-двойники -> кириллица (``xуй`` -> ``хуй``),
   цифры-двойники (``0`` -> ``о``, ``3`` -> ``з``). Длина текста при этом
   не меняется, поэтому найденные места совпадают с исходным текстом.
2. Ищутся три вида шаблонов:

   * ``_ANYWHERE`` — корни, которые встречаются только в мате, поэтому
     ловятся в любой части слова (с приставками: «за…», «на…», «по…»);
   * ``_WORD_START`` — корни, которые надёжны только в начале слова
     (иначе «употребляя» попало бы под «бля»);
   * ``_EXACT`` — короткие слова, которые ловятся только целиком.

3. Найденное слово маскируется: первая буква остаётся, остальные — ``*``.

Список не претендует на полноту — его легко расширить, не меняя код.
"""

from __future__ import annotations

import re

# Латинские и цифровые «двойники» кириллических букв.
_LOOKALIKE = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к", "m": "м",
    "o": "о", "p": "р", "t": "т", "x": "х", "y": "у", "0": "о", "3": "з",
    "6": "б", "ё": "е", "@": "а",
})

# Русский мат: корни, которые не встречаются в обычных словах, поэтому
# ловятся в любой части слова («спиздил», «распиздяй»).
_ANYWHERE = (
    "пизд", "пезд", "бляд", "мудак", "мудил", "мудоз", "пидор",
    "пидар", "гандон", "залуп", "шлюх", "сучар",
)

# Корни «ху…» и «еб…» прячутся внутри обычных слов («страхует»,
# «колебался», «ребенок»), поэтому ищем их только в начале слова или
# сразу после типичной приставки («на-», «за-», «по-», «долбо-» …).
_PREFIX = (r"(?:на|по|за|вы|до|от|отъ|съ|у|при|раз|рас|пере|под|недо|"
           r"долбо|долба|про|из|изъ|въ|о|об|объ|ни)?")
_ROOTS_AFTER_PREFIX = (r"ху[йяеёию]\w*", r"еб\w*")

# Грубые слова, надёжные только в начале слова.
_WORD_START = (
    # русский
    "бля", "сука", "суки", "суку", "сукой", "сукин", "дерьм", "говн",
    "жоп", "дебил", "идиот", "дурак", "придур", "тупиц", "ублюд",
    "засран", "мразь", "мрази",
    # казахский
    "сік", "сиктир", "қотақ", "қутақ", "ақымақ", "ақмақ", "есуас",
    "малғұн", "иттің", "шешеңді",
    # английский
    "fuck", "shit", "bitch", "asshole", "bastard", "cunt", "motherf",
    "idiot", "stupid", "moron", "dumbass",
)

# Короткие слова — только целиком.
_EXACT = ("дура", "дуры", "чмо", "лох", "тварь", "хули", "педик", "сучка",
          "dick", "fag", "wtf")

_CYR_RE = re.compile(
    r"\w*(?:" + "|".join(_ANYWHERE) + r")\w*"
    r"|\b" + _PREFIX + r"(?:" + "|".join(_ROOTS_AFTER_PREFIX) + r")"
    r"|\b(?:" + "|".join(w for w in _WORD_START if not w.isascii())
    + r")\w*"
    r"|\b(?:" + "|".join(w for w in _EXACT if not w.isascii()) + r")\b",
    re.IGNORECASE)
_LAT_RE = re.compile(
    r"\b(?:" + "|".join(w for w in _WORD_START if w.isascii()) + r")\w*"
    r"|\b(?:" + "|".join(w for w in _EXACT if w.isascii()) + r")\b",
    re.IGNORECASE)


def _mask(text: list[str], start: int, end: int) -> None:
    for i in range(start + 1, end):
        if not text[i].isspace():
            text[i] = "*"


def censor(text: str) -> str:
    """Вернуть текст, в котором бранные слова замаскированы звёздочками."""
    chars = list(text)
    lowered = text.lower()
    # Английские слова ищем в исходном тексте (без замены букв).
    for m in _LAT_RE.finditer(lowered):
        _mask(chars, m.start(), m.end())
    # Кириллические — в тексте с заменёнными двойниками.
    normalized = lowered.translate(_LOOKALIKE)
    for m in _CYR_RE.finditer(normalized):
        _mask(chars, m.start(), m.end())
    return "".join(chars)


def has_profanity(text: str) -> bool:
    """Есть ли в тексте бранные слова."""
    return censor(text) != text
